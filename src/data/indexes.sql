-- ============================================================================
-- 索引定义（在数据导入完成之后执行）
-- ============================================================================
-- 索引原理（常被追问）：
--   索引本质是一棵 B+ 树，把「全表扫描 O(n)」变成「树查找 O(log n)」。
--   代价有两个：① 占用额外磁盘空间；② 每次写入都要同步更新索引，所以不能滥建。
--   联合索引遵循「最左前缀原则」：(a, b) 这个索引可以服务 a 条件，也可以服务
--   (a, b) 组合条件，但服务不了「只查 b」的条件。
--   所以字段顺序要按「区分度高 + 查询频率高」排在前面。

-- ---------------------------------------------------------------------------
-- 1) 行为事件日志（10 万行，最高频的事实表）
-- ---------------------------------------------------------------------------
-- 最常用的查询：「某天发生了某个事件的所有用户」——算留存、算漏斗、算新增都用它
CREATE INDEX idx_event_date_name ON game_event_log (event_date, event_name);

-- 用户下钻分析：「某个用户的行为路径」，按时间排序
CREATE INDEX idx_event_user_time ON game_event_log (user_id, event_time);

-- 漏斗专用索引：先按「事件名 + 日期」锁定一批用户，再把 user_id 取出来做后续匹配。
-- 把 user_id 放在第三个字段，可以让这次查询直接从索引拿到 user_id，不回主表
-- （这就是「覆盖索引」的概念，能省掉一次随机 IO）。
CREATE INDEX idx_event_name_date_user ON game_event_log (event_name, event_date, user_id);

-- ---------------------------------------------------------------------------
-- 2) 每日快照（21.7 万行）
-- ---------------------------------------------------------------------------
-- DAU 是按日期扫描；留存是按「日期 + 是否活跃」过滤
CREATE INDEX idx_snapshot_date_active ON user_daily_snapshot (date, is_active);
-- 注意：这张表的主键 (user_id, date) 已经自带一个索引，能满足「按用户查」的场景，
-- 所以不要再重复建 idx(user_id, date)，那只是纯粹的写放大。

-- ---------------------------------------------------------------------------
-- 3) 招聘漏斗
-- ---------------------------------------------------------------------------
CREATE INDEX idx_hr_position_apply ON hr_recruitment_data (position_id, apply_time);
CREATE INDEX idx_hr_candidate ON hr_recruitment_data (candidate_id);
CREATE INDEX idx_hr_stage ON hr_recruitment_data (interview_stage, stage_index);

-- ---------------------------------------------------------------------------
-- 4) 维度表
-- ---------------------------------------------------------------------------
CREATE INDEX idx_dim_user_register_date ON dim_user (register_date);
CREATE INDEX idx_dim_user_channel ON dim_user (channel_id);

-- ---------------------------------------------------------------------------
-- 5) 真实明细表 user_game（84 万行）
-- ---------------------------------------------------------------------------
-- 这张表的主键是 (user_id, appid)，最左前缀是 user_id，
-- 所以「按 appid 反查玩家」这个场景用不上主键索引，必须单独建一个。
CREATE INDEX idx_user_game_appid ON user_game (appid);

-- ---------------------------------------------------------------------------
-- 6) 更新统计信息
-- ---------------------------------------------------------------------------
-- ANALYZE 会采样并记录每列的数据分布，供查询优化器估算「走索引还是全表扫描更划算」。
-- 不跑 ANALYZE 的话，SQLite 可能因为没有统计信息而选错执行计划。
ANALYZE;